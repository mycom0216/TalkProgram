namespace ChatApp.Common.Protocol;

/// <summary>서버와 클라이언트가 함께 쓰는 통신 규약(프로토콜)의 버전 번호 모음.</summary>
// ─────────────────────────────────────────────────────────────────────────────
// [파일 역할] 통신 규약(프로토콜)의 버전 번호.
// [왜] 서버와 클라이언트는 따로 배포된다. 서버만 새 버전이고 직원 PC의 사내톡은 옛 버전인 상황이 반드시 생긴다.
//      로그인할 때 버전을 주고받아, 너무 오래된 클라이언트에는 "업데이트하세요"라고 분명히 알려 준다.
//      (버전 확인이 없으면 옛 클라이언트가 모르는 패킷을 받고 이상하게 동작하거나 계속 끊긴다)
// [규칙] 패킷 모양이 "호환되지 않게" 바뀌면 Version을 올리고, 옛 클라이언트를 더 이상 받지 않을 때 MinSupported를 올린다.
// ─────────────────────────────────────────────────────────────────────────────
public static class ProtocolInfo
{
    /// <summary>이 프로그램(서버·클라이언트)이 쓰는 프로토콜 버전.</summary>
    /// <remarks>1 = 버전 번호가 없던 시절. 2 = 버전 확인 도입. 3 = 메시지 ID·읽음 표시·삭제·답장·공감·영구 방.</remarks>
    public const int Version = 3;

    /// <summary>서버가 받아 주는 가장 낮은 클라이언트 버전.</summary>
    public const int MinSupported = 3;
}
